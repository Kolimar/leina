// application/harness/adapters/windsurf.ts — Windsurf adapter. Workspace rules
// live in .devin/rules/ (preferred post-Cognition; leina consolidated on
// `.devin/` too) with a byte-identical mirror in .windsurf/rules/ for older
// clients. Hard platform limit: 12,000 chars per workspace rule file — rules
// are packed by priority (blocking first) and truncated to summaries beyond
// the budget, always pointing back at the canonical text.
//
// Deviation from the origin: leina's HarnessConfig has no `windsurf.mirrorLegacy`
// knob (unknown config keys are ignored by design), so the legacy mirror is
// always written — the origin's default behavior.

import path from "node:path";
import { type Rule, gatesOf } from "../../../domain/harness/model.ts";
import { fileExists } from "../io.ts";
import { COMPLETION_PROTOCOL } from "./digest.ts";
import {
  type AdapterRepoContext,
  type FileSet,
  type GeneratedFile,
  type PlatformAdapter,
  type RuleBundle,
} from "./types.ts";

export const WINDSURF_CHAR_LIMIT = 12_000;

const HEADER = `---
trigger: always_on
---
<!-- GENERATED by leina harness sync — edit .harness/rules/, then run \`leina harness sync\` -->

# Harness workflow

${COMPLETION_PROTOCOL}

## Rules
`;

const FOOTER = "\nFull rule text: `.harness/rules/` and `leina harness list`.\n";

function fullEntry(rule: Rule): string {
  const gates = gatesOf(rule);
  const enforcement = gates.length > 0 ? ` (enforced: ${gates.map((g) => g.type).join(", ")})` : "";
  return `\n### ${rule.id} [${rule.phase}/${rule.severity}]${enforcement}\n${rule.body.trim()}\n`;
}

function summaryEntry(rule: Rule): string {
  const summary = rule.summary ?? rule.body.trim().split("\n")[0] ?? "";
  return `\n- **${rule.id}** [${rule.phase}/${rule.severity}]: ${summary} — full text: .harness/rules/\n`;
}

export function packWindsurfRules(rules: Rule[]): { content: string; truncated: string[] } {
  const byPriority = [...rules].sort((a, b) =>
    a.severity === b.severity ? a.id.localeCompare(b.id) : a.severity === "blocking" ? -1 : 1,
  );

  const budget = WINDSURF_CHAR_LIMIT - HEADER.length - FOOTER.length;
  const truncated: string[] = [];
  const entries: string[] = [];
  let used = 0;

  // First pass: full bodies while they fit; second pass fallback to summaries.
  for (const rule of byPriority) {
    const full = fullEntry(rule);
    if (used + full.length <= budget) {
      entries.push(full);
      used += full.length;
      continue;
    }
    const summary = summaryEntry(rule);
    if (used + summary.length <= budget) {
      entries.push(summary);
      used += summary.length;
      truncated.push(rule.id);
    } else {
      truncated.push(rule.id);
    }
  }

  return { content: `${HEADER}${entries.join("")}${FOOTER}`, truncated };
}

export const windsurfAdapter: PlatformAdapter = {
  id: "windsurf",
  displayName: "Windsurf",
  capabilities: {
    contextInjection: true,
    preToolBlock: false,
    completionBlock: false,
    commitBlock: false,
  },
  verifySupport: "instructions-only",

  async detect(ctx: AdapterRepoContext): Promise<boolean> {
    return (
      (await fileExists(path.join(ctx.repoRoot, ".windsurf"))) ||
      (await fileExists(path.join(ctx.repoRoot, ".devin")))
    );
  },

  generate(bundle: RuleBundle, _ctx: AdapterRepoContext): Promise<FileSet> {
    const { content, truncated } = packWindsurfRules(bundle.rules);
    const warnings =
      truncated.length > 0
        ? [`12k char limit reached — truncated to summaries: ${truncated.join(", ")}`]
        : [];

    const files: GeneratedFile[] = [
      { path: ".devin/rules/harness-core.md", kind: "owned", content },
      { path: ".windsurf/rules/harness-core.md", kind: "owned", content },
    ];
    return Promise.resolve({ files, warnings });
  },
};
