// application/harness/adapters/cursor.ts — Cursor adapter. Cursor reads
// .cursor/rules/*.mdc. The always-apply core rule is kept ultra-compact
// (always-apply rules cost tokens on every request); individual rules ride as
// glob-scoped or agent-requested .mdc files. Real blocking is limited to the
// hooks beta: beforeShellExecution can deny git commit/push; afterFileEdit and
// stop are informational (edit log + advisory verify). Hook commands come from
// `config.hookCommand` (default "leina harness hook").

import path from "node:path";
import { type Rule, gatesOf } from "../../../domain/harness/model.ts";
import { fileExists } from "../io.ts";
import {
  type AdapterRepoContext,
  type FileSet,
  type GeneratedFile,
  type PlatformAdapter,
  type RuleBundle,
} from "./types.ts";

const GENERATED_HEADER =
  "<!-- GENERATED by leina harness sync — edit .harness/rules/, then run `leina harness sync` -->";

const CORE = `---
description: Harness workflow — completion is defined by leina harness verify exiting 0
alwaysApply: true
---
${GENERATED_HEADER}

# Harness workflow

- Before a non-trivial task: \`leina harness contract new --goal "<goal>" --type <type> --scope "<glob>"\`. Only files matching the declared scope may change.
- You are NOT done until \`leina harness verify\` exits 0. On failure, fix each gate using its report and re-run.
- Never weaken rules, skip tests, or edit \`.harness/\` to get past a gate.
- After 3 failed verify attempts, stop and report the failing gates verbatim.

Full rules: \`leina harness list\` · rule text in \`.harness/rules/\`.
`;

function mdcFileName(ruleId: string): string {
  return `harness-${ruleId.replaceAll("/", "-")}.mdc`;
}

function ruleToMdc(rule: Rule): string {
  const description = rule.summary ?? `Harness rule ${rule.id}`;
  const globs = rule.scope.paths?.join(",");
  const front = [
    "---",
    `description: ${description.replaceAll("\n", " ")}`,
    ...(globs !== undefined ? [`globs: ${globs}`] : []),
    "alwaysApply: false",
    "---",
  ].join("\n");
  const enforcement =
    gatesOf(rule).length > 0
      ? `\n\n_Enforced by \`leina harness verify\` (${gatesOf(rule)
          .map((g) => g.type)
          .join(", ")} gate) — severity: ${rule.severity}._`
      : `\n\n_Severity: ${rule.severity}._`;
  return `${front}\n${GENERATED_HEADER}\n\n${rule.body}${enforcement}\n`;
}

export const cursorAdapter: PlatformAdapter = {
  id: "cursor",
  displayName: "Cursor",
  capabilities: {
    contextInjection: true,
    preToolBlock: false,
    completionBlock: false,
    commitBlock: true, // beforeShellExecution deny (hooks beta)
  },
  verifySupport: "advisory-hooks",

  async detect(ctx: AdapterRepoContext): Promise<boolean> {
    return fileExists(path.join(ctx.repoRoot, ".cursor"));
  },

  generate(bundle: RuleBundle, _ctx: AdapterRepoContext): Promise<FileSet> {
    const files: GeneratedFile[] = [
      { path: ".cursor/rules/harness-core.mdc", kind: "owned", content: CORE },
      {
        // Hooks beta: beforeShellExecution can DENY — a real commit gate.
        // afterFileEdit/stop are informational (edit log + advisory verify).
        path: ".cursor/hooks.json",
        kind: "json-merge",
        mergeStrategy: "cursor-hooks",
        content: JSON.stringify({
          beforeShellExecution: [`${bundle.config.hookCommand} cursor-shell`],
          afterFileEdit: [`${bundle.config.hookCommand} cursor-after-edit`],
          stop: [`${bundle.config.hookCommand} cursor-stop`],
        }),
      },
    ];
    for (const rule of bundle.rules) {
      files.push({
        path: `.cursor/rules/${mdcFileName(rule.id)}`,
        kind: "owned",
        content: ruleToMdc(rule),
      });
    }
    return Promise.resolve({ files, warnings: [] });
  },
};
