// application/harness/adapters/opencode.ts — OpenCode adapter. OpenCode reads
// AGENTS.md natively (covered by the agentsmd adapter) and an `instructions`
// array in opencode.json. The full compiled rule text goes to
// .harness/generated/opencode-rules.md — no size-limit pressure there. Tool
// blocking rides on the generated plugin below.
//
// Thin generated plugin: ALL enforcement logic lives in the leina CLI, so this
// file never goes stale — it only maps OpenCode tool calls onto the same
// `harness hook` events every other platform uses (command prefix from
// `config.hookCommand`, default "leina harness hook"), and throws to block —
// only on the hook's block status (exit 2); a missing CLI warns and allows.

import path from "node:path";
import { fileExists } from "../io.ts";
import { renderInstructionBlock } from "./digest.ts";
import {
  type AdapterRepoContext,
  type FileSet,
  type PlatformAdapter,
  type RuleBundle,
} from "./types.ts";

const pluginSource = (hookCommand: string): string => {
  const parts = hookCommand.split(/\s+/).filter(Boolean);
  const cmd = JSON.stringify(parts[0] ?? "leina");
  const baseArgs = JSON.stringify(parts.slice(1));
  // Note: the generated plugin lazy-imports node:child_process (the origin used
  // a static import). Functionally identical in OpenCode's ESM plugin host, and
  // it keeps this adapter's source clean under leina's arch-rule-3 scanner,
  // which reads import lines textually.
  // Only the hook's documented block status (exit 2) blocks. A CLI that is not
  // on PATH (spawn ENOENT), a timeout or any other status is a malfunction,
  // not a verdict — warn and allow, or one missing binary wedges every edit.
  // (The command stays `config.hookCommand`, not an absolute path: this file is
  // committed, and a machine-specific path would break it for everyone else.)
  return `// GENERATED by leina harness sync — edit .harness/rules/, then run \`leina harness sync\`
const { execFileSync } = await import("node:child_process")

const BLOCK_STATUS = 2

export const HarnessPlugin = async ({ directory }) => {
  const run = (event, payload) => {
    try {
      execFileSync(${cmd}, [...${baseArgs}, event], {
        cwd: directory,
        input: JSON.stringify(payload ?? {}),
        stdio: ["pipe", "pipe", "pipe"],
        timeout: 600000,
      })
      return null
    } catch (err) {
      const stderr = err && err.stderr ? String(err.stderr).trim() : ""
      if (err && err.status === BLOCK_STATUS) return stderr || "blocked by harness"
      const reason = (err && (err.code || (err.status != null ? "exit " + err.status : err.signal))) || "error"
      console.warn("[leina harness] " + event + " hook did not run (" + reason + ") — allowing" + (stderr ? ": " + stderr : ""))
      return null
    }
  }

  return {
    "tool.execute.before": async (input, output) => {
      const args = (output && output.args) || {}
      let event = null
      let payload = null
      if (input.tool === "edit" || input.tool === "write") {
        event = "pre-edit"
        payload = { tool_input: { file_path: args.filePath ?? args.file_path ?? args.path } }
      } else if (input.tool === "bash") {
        event = "pre-bash"
        payload = { tool_input: { command: args.command } }
      }
      if (!event) return
      const blocked = run(event, payload)
      if (blocked) throw new Error(blocked)
    },
    event: async ({ event }) => {
      if (event && event.type === "session.idle") run("idle", {})
    },
  }
}
`;
};

export const opencodeAdapter: PlatformAdapter = {
  id: "opencode",
  displayName: "OpenCode",
  capabilities: {
    contextInjection: true,
    preToolBlock: true, // generated plugin throws on `harness hook` exit 2 (block)
    completionBlock: false, // session.idle is only an advisory nudge
    commitBlock: true, // pre-bash blocks git commit/push while gates fail
  },
  verifySupport: "blocking-hooks",

  async detect(ctx: AdapterRepoContext): Promise<boolean> {
    return (
      (await fileExists(path.join(ctx.repoRoot, "opencode.json"))) ||
      (await fileExists(path.join(ctx.repoRoot, ".opencode")))
    );
  },

  generate(bundle: RuleBundle, _ctx: AdapterRepoContext): Promise<FileSet> {
    const rulesFile = ".harness/generated/opencode-rules.md";
    const body = [
      "<!-- GENERATED by leina harness sync — edit .harness/rules/, then run `leina harness sync` -->",
      renderInstructionBlock(bundle, { includeContractTemplate: true }),
    ].join("\n\n");

    return Promise.resolve({
      files: [
        { path: rulesFile, kind: "owned", content: `${body}\n` },
        {
          path: "opencode.json",
          kind: "json-merge",
          mergeStrategy: "opencode-instructions",
          content: rulesFile,
        },
        { path: ".opencode/plugin/harness.js", kind: "owned", content: pluginSource(bundle.config.hookCommand) },
      ],
      warnings: [],
    });
  },
};
