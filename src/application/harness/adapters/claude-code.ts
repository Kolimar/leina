// application/harness/adapters/claude-code.ts — Claude Code adapter.
//
// DESIGN CHANGE vs. the origin harness-framework: this adapter does NOT write
// hooks into .claude/settings.json (the origin json-merged SessionStart /
// PreToolUse / Stop entries there). Inside leina, enforcement for Claude Code
// and Devin travels through the agent-gate that `leina init` already installs —
// wiring a second, parallel hook chain from here would double-fire on every
// tool call and leave two owners fighting over the same settings file. The
// blocking branch of the agent-gate lands in a later stage; this adapter only
// projects instructions:
//   · a managed block in CLAUDE.md (compact rule digest),
//   · the owned `harness-workflow` skill,
//   · one owned skill per golden-path recipe.

import path from "node:path";
import { fileExists } from "../io.ts";
import { renderInstructionBlock, COMPLETION_PROTOCOL } from "./digest.ts";
import {
  type AdapterRepoContext,
  type FileSet,
  type PlatformAdapter,
  type RuleBundle,
} from "./types.ts";

const SKILL = `---
name: harness-workflow
description: "Harness task workflow: declare a contract, work inside its scope, and pass every gate before claiming completion. Trigger: at the start of any non-trivial coding task in this repository."
---

# Harness task workflow

This repository is governed by a harness: rules guide the work and executable
gates verify it. Completion is defined by \`leina harness verify\` exiting 0 — not
by your own judgement.

## Procedure

1. **Interview first.** Ask the user clarifying questions until goal, scope
   and acceptance criteria are unambiguous, reflect your understanding back,
   and get a yes. Check \`leina harness contract show\` — if an unrelated
   contract is still active, ask the user whether to close it
   (\`leina harness contract end\`) before opening a new one.
2. **Contract.** Run:
   \`leina harness contract new --goal "<goal>" --type <feature|bugfix|refactor|docs|chore> --scope "<glob>" [--scope "<glob>" ...]\`
   List acceptance criteria with repeated \`--criterion "<text>"\` flags.
3. **Plan.** If the plan rule is active, write your plan to
   \`.harness/state/current/plan.md\` before editing code.
4. **Work inside the scope.** Edits outside the declared globs are blocked by a
   hook. If a file genuinely must change, amend the contract first:
   \`leina harness contract edit --add-scope "<glob>"\` and say why.
5. **Verify.** Run \`leina harness verify\`. Fix every failing gate using its
   report (command, output, remediation). Re-run until it exits 0.
6. **Deliver.** Close the task with \`leina harness contract end\`.

## Hard rules

- Never edit \`.harness/\` rules or config to get past a gate.
- Never skip, delete, or weaken a test to make the suite pass.
- If a gate still fails after 3 honest attempts, stop and report the failing
  gates verbatim instead of claiming success.
`;

export const claudeCodeAdapter: PlatformAdapter = {
  id: "claude-code",
  displayName: "Claude Code",
  // Capabilities describe what the platform can enforce end-to-end: context
  // injection via CLAUDE.md, and tool/commit/completion blocking via leina's
  // agent-gate (installed by `leina init`, not by this adapter — see header).
  capabilities: {
    contextInjection: true,
    preToolBlock: true,
    completionBlock: true,
    commitBlock: true,
  },
  verifySupport: "blocking-hooks",

  async detect(ctx: AdapterRepoContext): Promise<boolean> {
    return (
      (await fileExists(path.join(ctx.repoRoot, ".claude"))) ||
      (await fileExists(path.join(ctx.repoRoot, "CLAUDE.md")))
    );
  },

  generate(bundle: RuleBundle, _ctx: AdapterRepoContext): Promise<FileSet> {
    // CLAUDE.md carries the compact digest (kept well under context-budget
    // pressure); the agent-gate injects contract state at session time.
    const block = [
      renderInstructionBlock(bundle, { includeContractTemplate: false }),
      "The `harness-workflow` skill describes the full task procedure.",
    ].join("\n\n");

    const files = [
      { path: "CLAUDE.md", kind: "managed-block" as const, blockId: "harness-core", content: block },
      { path: ".claude/skills/harness-workflow/SKILL.md", kind: "owned" as const, content: SKILL },
      ...bundle.recipes.map((recipe) => ({
        path: `.claude/skills/harness-recipe-${recipe.name}/SKILL.md`,
        kind: "owned" as const,
        content: `---\nname: harness-recipe-${recipe.name}\ndescription: "${recipe.description.replaceAll('"', '\\"')} Trigger: when the task matches this recipe${recipe.taskType ? ` (task type: ${recipe.taskType})` : ""}."\n---\n<!-- GENERATED by leina harness sync — edit .harness/recipes/, then run \`leina harness sync\` -->\n\n${recipe.body}\n`,
      })),
    ];
    return Promise.resolve({ files, warnings: [] });
  },
};

export { COMPLETION_PROTOCOL };
